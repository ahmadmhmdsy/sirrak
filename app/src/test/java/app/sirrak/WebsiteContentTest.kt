package app.sirrak

import java.io.File
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * P3.8 keeps the public site honest: the checked-in generator output must still match the data files
 * (website/site.json, website/content/en.json, website/content/ar.json, website/content/policies.json),
 * the brand source (store/graphics/brand.json) and the shipped app config (app/src/main/assets/config/app.json).
 *
 * The site is generated by scripts/build-site.ps1 -- this test is the drift alarm that tells us to
 * re-run it and commit website/dist. It is structural, not a browser test: the renderer is validated
 * by scripts/validate-site.ps1, this test protects the data-to-page contract.
 */
class WebsiteContentTest {

    private val repositoryRoot = File("..")
    private val websiteDir = File(repositoryRoot, "website")
    private val distDir = File(websiteDir, "dist")
    private val site = parse(File(websiteDir, "site.json"))
    private val brand = parse(File(repositoryRoot, "store/graphics/brand.json"))
    private val policies = parse(File(websiteDir, "content/policies.json"))
    private val appConfig = parse(File(repositoryRoot, "app/src/main/assets/config/app.json"))

    private fun parse(file: File): JsonObject {
        assertTrue("missing data file: " + file.absolutePath, file.isFile)
        return Json.parseToJsonElement(file.readText()).jsonObject
    }

    private fun text(node: JsonObject, key: String): String =
        node.getValue(key).jsonPrimitive.content

    private fun stringArray(node: JsonObject, key: String): List<String> =
        node.getValue(key).jsonArray.map { it.jsonPrimitive.content }

    private fun siteUrl(): String = text(site, "siteUrl")

    private fun releaseDate(): String =
        text(site.getValue("product").jsonObject, "releaseDate")

    private fun languages(): List<JsonObject> = site.getValue("languages").jsonArray.map { it.jsonObject }

    private fun language(code: String): JsonObject =
        languages().firstOrNull { it.getValue("code").jsonPrimitive.content == code }
            ?: error("site.json has no language '" + code + "'")

    private fun landingFile(code: String): File =
        File(distDir, text(language(code), "path") + text(site.getValue("pages").jsonObject.getValue("landing").jsonObject, "file"))

    private fun policyFile(code: String, page: String, suffix: String): File =
        File(distDir, text(language(code), "path") + suffix + "/index.html")

    private fun canonical(code: String, page: String, suffix: String): String =
        siteUrl() + text(language(code), "path") + suffix

    private fun content(code: String): JsonObject =
        parse(File(websiteDir, "content/" + code + ".json"))

    private fun addKeyPaths(node: JsonElement, prefix: String, output: MutableSet<String>) {
        when (node) {
            is JsonObject -> node.forEach { (key, value) ->
                val path = if (prefix.isEmpty()) key else prefix + "." + key
                output.add(path)
                addKeyPaths(value, path, output)
            }
            is JsonArray -> node.forEachIndexed { index, value ->
                addKeyPaths(value, prefix + "[" + index + "]", output)
            }
            else -> Unit
        }
    }

    private fun keyPaths(node: JsonElement): Set<String> {
        val paths = linkedSetOf<String>()
        addKeyPaths(node, "", paths)
        return paths
    }

    private fun htmlEscape(value: String): String =
        value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;")

    private fun pngSize(file: File): Pair<Int, Int> {
        assertTrue("missing image: " + file.absolutePath, file.isFile)
        val bytes = file.readBytes()
        assertEquals("PNG signature in " + file.name, 0x89.toByte(), bytes[0])
        fun int(at: Int): Int =
            ((bytes[at].toInt() and 0xFF) shl 24) or
                ((bytes[at + 1].toInt() and 0xFF) shl 16) or
                ((bytes[at + 2].toInt() and 0xFF) shl 8) or
                (bytes[at + 3].toInt() and 0xFF)
        return int(16) to int(20)
    }

    @Test
    fun dataSourcesParseAndTranslationsHaveTheSameShape() {
        assertEquals(1, site.getValue("schemaVersion").jsonPrimitive.int)
        assertEquals(1, policies.getValue("schemaVersion").jsonPrimitive.int)
        assertEquals(listOf("en", "ar"), languages().map { it.getValue("code").jsonPrimitive.content })
        for (code in listOf("en", "ar")) {
            assertTrue("content/" + code + ".json must not be empty", content(code).isNotEmpty())
        }
        assertEquals(
            "English and Arabic landing copy must keep the same key structure",
            keyPaths(content("en")),
            keyPaths(content("ar")),
        )
        val privacy = policies.getValue("privacy").jsonObject
        assertEquals(keyPaths(privacy.getValue("en")), keyPaths(privacy.getValue("ar")))
        val security = policies.getValue("security").jsonObject
        assertEquals(keyPaths(security.getValue("en")), keyPaths(security.getValue("ar")))
        assertEquals(
            "hosted policy date must equal the product release date",
            releaseDate(),
            text(policies, "updated"),
        )
    }

    @Test
    fun productMetadataMatchesTheBuildAndPagesExist() {
        val gradle = File(repositoryRoot, "app/build.gradle.kts").readText()
        val versionName = Regex("versionName\\s*=\\s*\"([^\"]+)\"").find(gradle)?.groupValues?.get(1)
        assertNotNull("versionName must be defined in app/build.gradle.kts", versionName)
        assertEquals("site.json version must follow the app version", versionName, text(site.getValue("product").jsonObject, "version"))
        assertTrue(
            "release date must be an ISO date",
            Regex("^\\d{4}-\\d{2}-\\d{2}$").matches(releaseDate()),
        )
        val expected = mapOf("en" to "", "ar" to "ar/")
        for ((code, path) in expected) {
            assertEquals(path, text(language(code), "path"))
            assertTrue("missing landing page for " + code, landingFile(code).isFile)
            assertTrue("missing privacy policy page for " + code, policyFile(code, "privacy", "privacy").isFile)
            assertTrue("missing security policy page for " + code, policyFile(code, "security", "security").isFile)
        }
    }

    @Test
    fun brandPaletteMarkAndFontsFlowIntoTheGeneratedSite() {
        val palette = brand.getValue("palette").jsonObject
        val css = File(distDir, "assets/site.css").readText()
        palette.forEach { (role, value) ->
            val hex = value.jsonPrimitive.content.uppercase()
            assertTrue("brand palette token " + role + " (" + hex + ") is missing from site.css", css.contains(hex, ignoreCase = true))
        }
        val markPaths = brand.getValue("mark").jsonObject.getValue("paths").jsonArray
            .map { it.jsonObject.getValue("d").jsonPrimitive.content }
        for (code in listOf("en", "ar")) {
            val html = landingFile(code).readText()
            markPaths.forEach { path ->
                assertTrue("brand mark path is missing from the " + code + " landing page", html.contains(path))
            }
        }
        val fonts = site.getValue("assets").jsonObject.getValue("fonts").jsonObject
        assertTrue("at least four site fonts are declared", fonts.size >= 4)
        fonts.forEach { (role, value) ->
            val file = File(distDir, value.jsonPrimitive.content)
            assertTrue("missing generated font " + role + ": " + file.absolutePath, file.isFile)
            assertTrue("font " + role + " is suspiciously small", file.length() > 100_000)
        }
    }

    @Test
    fun certificateAndAppPolicyLinksPointAtTheSamePublicSite() {
        val certificate = text(site, "certificateSha256")
        assertTrue("certificate fingerprint must be 64 uppercase hex characters", Regex("^[0-9A-F]{64}$").matches(certificate))
        for (code in listOf("en", "ar")) {
            assertTrue(
                "the " + code + " landing page must show the signing certificate fingerprint",
                landingFile(code).readText().contains(certificate),
            )
        }
        val privacy = appConfig.getValue("privacy").jsonObject
        assertEquals(
            "app config must link the hosted privacy policy",
            siteUrl() + "privacy/",
            text(privacy, "policyUrl"),
        )
        assertEquals(
            "app config must link the hosted security policy",
            siteUrl() + "security/",
            text(privacy, "securityUrl"),
        )
        assertEquals(
            "app config must link the project issue tracker",
            text(site, "issuesUrl") + "/new/choose",
            text(privacy, "reportIssueUrl"),
        )
    }

    @Test
    fun policyPagesRenderEveryParagraphOfTheHostedPolicy() {
        val year = releaseDate().substring(0, 4)
        for (page in listOf("privacy", "security")) {
            val pageNode = policies.getValue(page).jsonObject
            for (code in listOf("en", "ar")) {
                val localized = pageNode.getValue(code).jsonObject
                val file = policyFile(code, page, page)
                val html = file.readText()
                val sections = localized.getValue("sections").jsonArray
                assertTrue("policy " + page + "/" + code + " must have sections", sections.size >= 4)
                sections.forEach { element ->
                    val heading = element.jsonObject.getValue("heading").jsonPrimitive.content
                    assertTrue(
                        "policy " + page + "/" + code + " is missing the section heading: " + heading,
                        html.contains(htmlEscape(heading)),
                    )
                }
                assertTrue(
                    "policy " + page + "/" + code + " must show the update year " + year,
                    html.contains(year),
                )
                assertTrue(
                    "policy " + page + "/" + code + " must link back to the landing page",
                    html.contains("policy-back"),
                )
            }
        }
    }

    @Test
    fun sitemapRobotsManifestAndLlmsDescribeTheSameSevenPages() {
        val sitemap = File(distDir, "sitemap.xml").readText()
        val canonicalPages = mutableListOf<String>()
        for (code in listOf("en", "ar")) {
            canonicalPages.add(canonical(code, "landing", ""))
            canonicalPages.add(canonical(code, "privacy", "privacy/"))
            canonicalPages.add(canonical(code, "security", "security/"))
        }
        canonicalPages.forEach { url ->
            assertTrue("sitemap is missing " + url, sitemap.contains("<loc>" + url + "</loc>"))
        }
        assertEquals("sitemap must list exactly six pages", 6, Regex("<loc>").findAll(sitemap).count())
        assertEquals(
            "sitemap must carry an x-default alternate for every page",
            canonicalPages.size,
            Regex("hreflang=\"x-default\"").findAll(sitemap).count(),
        )
        assertTrue("sitemap must carry the release date", sitemap.contains(releaseDate()))
        val robots = File(distDir, "robots.txt").readText()
        assertTrue("robots.txt must publish the sitemap", robots.contains(siteUrl() + "sitemap.xml"))
        val manifest = Json.parseToJsonElement(File(distDir, "manifest.webmanifest").readText()).jsonObject
        val icons = manifest.getValue("icons").jsonArray.map { it.jsonObject }
        assertTrue("manifest needs a 192 icon", icons.any { it.getValue("sizes").jsonPrimitive.content == "192x192" })
        assertTrue("manifest needs a 512 icon", icons.any { it.getValue("sizes").jsonPrimitive.content == "512x512" })
        assertEquals(
            "manifest theme colour must follow the brand ground token",
            brand.getValue("palette").jsonObject.getValue("ground").jsonPrimitive.content.uppercase(),
            text(manifest, "theme_color").uppercase(),
        )
        val llms = File(distDir, "llms.txt").readText()
        assertTrue("llms.txt must describe the public site", llms.contains(siteUrl()) && llms.length > 400)
    }

    @Test
    fun generatedAssetsAndPublicDocsCarryNoDraftsOrLocalPaths() {
        val og = pngSize(File(distDir, "assets/og-image.png"))
        assertEquals(1200 to 630, og)
        assertEquals(512 to 512, pngSize(File(distDir, "assets/icon-512.png")))
        assertEquals(192 to 192, pngSize(File(distDir, "assets/icon-192.png")))
        val screenshots = site.getValue("assets").jsonObject.getValue("screenshots").jsonObject
        assertTrue("at least six screenshots are published", screenshots.size >= 6)
        screenshots.forEach { (name, value) ->
            val file = File(distDir, value.jsonPrimitive.content)
            assertEquals("screenshot " + name + " must be a 720x1280 app capture", 720 to 1280, pngSize(file))
        }
        val forbidden = listOf("D:/sirrak", "D:\\sirrak", "E:/rea", "file:///", "localhost", "127.0.0.1")
        val htmlFiles = distDir.walkTopDown().filter { it.isFile && it.extension == "html" }.toList()
        assertEquals("the generated site must contain exactly six pages plus 404", 7, htmlFiles.size)
        htmlFiles.forEach { file ->
            val text = file.readText()
            forbidden.forEach { marker ->
                assertTrue(marker + " leaked into " + file.name, !text.contains(marker))
            }
            assertTrue("TODO leaked into " + file.name, !text.contains("TODO"))
        }
        for (doc in listOf("README.md", "PRIVACY.md", "SECURITY.md")) {
            val file = File(repositoryRoot, doc)
            assertTrue(doc + " must exist", file.isFile)
            val text = file.readText()
            assertTrue(doc + " must link the public site", text.contains(siteUrl()))
            assertTrue(doc + " must not call the policies unpublished", !text.contains("not yet published", ignoreCase = true))
            forbidden.forEach { marker ->
                assertTrue(marker + " leaked into " + doc, !text.contains(marker))
            }
        }
    }
}
